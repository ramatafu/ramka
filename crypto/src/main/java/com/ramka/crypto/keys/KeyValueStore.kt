package com.ramka.crypto.keys

/**
 * Абстракция хранилища пар ключ-значение для секретов, которыми оперирует
 * [KeyManager]. Единственная причина существования этого интерфейса —
 * тестируемость: реальная реализация ([com.ramka.crypto.securestorage.SecureKeyStore])
 * использует EncryptedSharedPreferences и Android Keystore, а unit-тесты модуля
 * crypto (pure JVM, JUnit4, без Android) подставляют простую in-memory реализацию
 * (см. тестовый sourceSet — `InMemoryKeyValueStore`).
 *
 * КОНТРАКТ, обязательный для любой реализации:
 * - [getBytes] возвращает НОВЫЙ массив при каждом вызове — никогда не отдаёт ссылку
 *   на внутренний массив хранилища. Вызывающий код (см. [KeyManager]) вправе
 *   обнулять полученный массив после использования (гигиена ключевого материала);
 *   если реализация вернёт массив по ссылке, это обнуление испортит сами хранимые
 *   данные, и повторное чтение того же ключа вернёт мусор.
 * - [putBytes] сохраняет КОПИЮ переданного массива, а не ссылку на него — вызывающий
 *   код может обнулить свой `value` сразу после вызова, не влияя на хранилище.
 * - Значения, проходящие через реализации этого интерфейса, никогда не логируются.
 *
 * Нарушение первого пункта — реальный найденный баг (см. `InMemoryKeyValueStore` до
 * исправления): вызывающий код обнулял временный массив, полученный из `getBytes`,
 * что при отдаче по ссылке зануляло сами хранимые байты.
 */
interface KeyValueStore {
    fun getBytes(key: String): ByteArray?
    fun putBytes(key: String, value: ByteArray)
}
